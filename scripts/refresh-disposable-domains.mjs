// Rewrites convex/disposableDomains.ts from the community-maintained list of
// temporary-inbox domains (github.com/disposable-email-domains/disposable-email-domains,
// CC0). The list is committed so the check runs offline inside Convex: no MX
// lookups, no third-party call on a signup.
//
//   node scripts/refresh-disposable-domains.mjs            # fetch the latest list
//   node scripts/refresh-disposable-domains.mjs ./list.conf # or use a downloaded copy
//
// Then run the tests (tests/email-identity.test.ts) and commit the file. Domains
// the list misses go in EXTRA_DISPOSABLE in convex/emailIdentity.ts, not here.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const out = resolve(dirname(fileURLToPath(import.meta.url)), "..", "convex", "disposableDomains.ts");

const local = process.argv[2];
const text = local ? readFileSync(local, "utf8") : await (await fetch(SOURCE)).text();

const domains = [
  ...new Set(
    text
      .split(/\r?\n/)
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line && !line.startsWith("#") && /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(line)),
  ),
].sort();

// a short list means a bad download (an HTML error page, a moved file): refuse it
if (domains.length < 3000) throw new Error(`only ${domains.length} domains: not writing`);
for (const must of ["mailinator.com", "guerrillamail.com", "yopmail.com"]) {
  if (!domains.includes(must)) throw new Error(`${must} is missing: not writing`);
}
for (const never of ["gmail.com", "outlook.com", "yahoo.com", "icloud.com", "hotmail.com"]) {
  if (domains.includes(never)) throw new Error(`${never} is on the list: not writing`);
}

const body = [
  "/**",
  " * Temporary-inbox domains: generated by scripts/refresh-disposable-domains.mjs",
  " * from github.com/disposable-email-domains/disposable-email-domains (CC0).",
  " * Do not edit by hand; re-run the script to refresh it. Read through",
  " * convex/emailIdentity.ts isDisposableEmail, which also checks subdomains.",
  " */",
  `export const DISPOSABLE_DOMAINS_UPDATED = "${new Date().toISOString().slice(0, 10)}";`,
  "",
  "export const DISPOSABLE_DOMAINS: readonly string[] = [",
  ...domains.map((d) => `  "${d}",`),
  "];",
  "",
].join("\n");

writeFileSync(out, body);
console.log(`wrote ${domains.length} domains to ${out}`);
